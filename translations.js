function applyTranslations(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key] !== undefined) {
      el.textContent = translations[lang][key];
    }
  });

  // Update placeholders
  const placeholders = {
    en: { name: 'Jane Smith', company: 'Acme Corp', email: 'jane@acme.com', message: 'Tell us about your project or challenge...' },
    ro: { name: 'Ion Popescu', company: 'Firma SA', email: 'ion@firma.ro', message: 'Spune-ne despre proiectul sau provocarea ta...' }
  };
  const p = placeholders[lang];
  const nameEl = document.getElementById('pv-name');
  const companyEl = document.getElementById('pv-company');
  const emailEl = document.getElementById('pv-email');
  const msgEl = document.getElementById('pv-msg');
  if (nameEl) nameEl.placeholder = p.name;
  if (companyEl) companyEl.placeholder = p.company;
  if (emailEl) emailEl.placeholder = p.email;
  if (msgEl) msgEl.placeholder = p.message;

  // Update html lang attribute
  document.documentElement.lang = lang;

  // Update lang toggle labels
  const isEN = lang === 'en';
  document.querySelectorAll('.lang-active').forEach(el => el.textContent = isEN ? 'EN' : 'RO');
  document.querySelectorAll('.lang-other').forEach(el => el.textContent = isEN ? 'RO' : 'EN');

  localStorage.setItem('pvs-lang', lang);

  if (typeof window.pvsOnLangChange === 'function') window.pvsOnLangChange(lang);
}

function toggleLang() {
  const current = localStorage.getItem('pvs-lang') || 'en';
  applyTranslations(current === 'en' ? 'ro' : 'en');
}

// Apply saved or default language on load
(function () {
  const saved = localStorage.getItem('pvs-lang') || 'en';
  if (saved !== 'en') applyTranslations(saved);
})();
